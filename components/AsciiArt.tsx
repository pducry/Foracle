type AsciiArtProps = {
  seed?: number;
  className?: string;
};

export function AsciiArt({ seed, className = "" }: AsciiArtProps) {
  const art = useMemo(() => {
    const index = seed !== undefined
      ? Math.abs(seed) % ASCII_ARTS.length
      : Math.floor(Math.random() * ASCII_ARTS.length);
    return ASCII_ARTS[index];
  }, [seed]);

  return (
    <div className={`w-full rounded-xl bg-[var(--color-bg-tertiary)] overflow-hidden ${className}`}>
      <pre
        className="text-[var(--color-text-muted)]/40 text-[8px] md:text-[10px] leading-[1.2] font-mono
          whitespace-pre overflow-hidden flex items-center justify-center p-6 min-h-[200px]"
      >
        {art}
      </pre>
    </div>
  );
}
